// Post-build: write dist/sw.js with a precache list generated from the files actually in
// dist/ (so a missing file can't make cache.addAll() fail silently) and a cache name
// derived from their contents (so it changes whenever any asset does — no manual bump).
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const DIST = 'dist';
// Large or optional files are cached on first use instead of up front.
const LAZY = [/^demo\//, /^help\//];

const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files.push(relative(DIST, p).split('\\').join('/'));
  }
})(DIST);

const precache = files.filter(f => f !== 'sw.js' && !LAZY.some(re => re.test(f))).sort();
const hash = createHash('sha256');
for (const f of precache) hash.update(f).update(readFileSync(join(DIST, f)));
hash.update(readFileSync(new URL(import.meta.url))); // SW logic changes also get a fresh cache
const version = hash.digest('hex').slice(0, 12);
const urls = precache.map(f => (f === 'index.html' ? './' : `./${f}`));

writeFileSync(join(DIST, 'sw.js'), `// Generated by scripts/build-sw.mjs — do not edit.
const CACHE = 'yah-${version}';
const RUNTIME = 'yah-runtime';
const PRECACHE = ${JSON.stringify(urls, null, 0)};
const MATCH = { ignoreSearch: true, ignoreVary: true };

self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith('yah-') && k !== CACHE && k !== RUNTIME).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

self.addEventListener('fetch', e => {
  const req = e.request, url = new URL(req.url);
  // Only our own files. Map tiles and anything third-party go straight to the network.
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;

  // The page: network first (so a new deploy shows up), cached copy when offline.
  if (req.mode === 'navigate') {
    e.respondWith(Promise.race([
      fetch(req),
      new Promise((_, reject) => setTimeout(() => reject(new Error('slow')), 4000)),
    ]).catch(() => caches.match('./', MATCH).then(r => r || caches.match(req, MATCH))));
    return;
  }

  // Everything else: cache first; otherwise fetch and keep a copy (demo map, help images).
  // ignoreVary: module scripts are requested with an Origin header that the precache
  // requests didn't have, so a 'Vary: Origin' response would otherwise never match offline.
  e.respondWith(caches.match(req, MATCH).then(hit => hit || fetch(req).then(res => {
    if (res.ok) { const copy = res.clone(); caches.open(RUNTIME).then(c => c.put(req, copy)); }
    return res;
  })));
});
`);
console.log(`sw.js: cache yah-${version}, ${urls.length} files precached (${files.length - urls.length - 0} lazy)`);
